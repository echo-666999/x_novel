<?php

namespace App\AI;

final class NarrativeProsePolicy
{
    /**
     * 规划阶段的结构表达约束。
     *
     * 对应版本由 config/prompts.php 的 policies.planning 管理；修改本文本时必须同步升级。
     */
    public static function planning(): string
    {
        return <<<'PROMPT'
规划内容必须写清：谁要做什么、受到什么阻力、作出什么选择、造成什么可观察结果，以及该结果如何引发下一步。

相邻 Volume、Arc、Beat、Milestone 或 Scene 必须承担不同的推进职责，并产生新的信息、选择、关系变化、资源变化、风险升级或剧情结果。不得把同一次回忆、身份确认、情绪反应、信息揭示或行动准备拆成多个结构单元反复书写；不得为了填满章节预算延迟已经可以发生的结果。

主题必须通过人物选择和后果体现，不得用“展现、体现、深化、凸显、升华、命运齿轮、时代洪流”等抽象标签代替剧情。目标、完成条件和验收条件必须能由正文中的动作、对白、物证、决定或状态变化验证，避免使用“意识到、感受到、理解了某种意义”等无法独立验收的结论。

各字段只表达自身职责，不要在 summary、goal、acceptance_criteria、must_include 等字段中换词重复同一内容。语言应具体、简洁、自然，避免整齐排比、宣传文案和空泛升华。
PROMPT;
    }

    /**
     * Scene Writer 与 Rewrite 共用的正文表达约束。
     *
     * 对应版本由 config/prompts.php 的 policies.writing 管理；修改本文本时必须同步升级。
     */
    public static function writing(): string
    {
        return <<<'PROMPT'
正文必须像人物正在经历事件。场景中的动作、对白、观察和心理活动都应服务当前目标、阻力、选择或后果；描写可以放慢一瞬，但必须建立空间、人物状态、关系压力或即将发生的变化。不得把计划字段、人物标签、背景资料或主题结论换一种说法塞回正文。

严格停留在当前 POV 能够感知、回忆和推断的范围内。优先用动作、带目的的对白、具体物件、环境变化、身体反应和行为后果传递信息；必要的时间、地点与因果过渡可以直接简洁叙述，不要为了“展示”而把一句话能说清的内容扩成无效表演。

同一段记忆、意象、动作、身体感觉、判断或情绪不得在没有新信息和新后果时反复出现。回扣必须改变人物当下的选择、理解、关系或风险，不能只是换词重播。不得反复使用“他意识到、他明白、这意味着、这不是……而是……、这一刻、仿佛命运或时代”等解释性套句；不得在每段末尾总结意义。

不同人物的对白必须符合各自身份、知识、目的和关系远近。对白应包含试探、回避、误解、隐瞒、打断或答非所问等真实反应，不要让所有人使用同一种句式，也不要把潜台词全部说透。

句长、段落长度和收束方式应随动作强弱自然变化。避免整齐排比、连续同构短段、四字词堆叠、泛化比喻和空泛升华。场景结尾优先停在具体行动、决定、新信息、关系变化或迫近风险上，不用作者总结代替悬念。不得为了规避套式而故意写成碎句、晦涩句，删掉必要因果，或编造新事实填充篇幅。
PROMPT;
    }

    /**
     * Reviewer 用于识别重复和机器化表达的审校边界。
     *
     * 对应版本由 config/prompts.php 的 policies.reviewing 管理；修改本文本时必须同步升级。
     */
    public static function reviewing(): string
    {
        return <<<'PROMPT'
审校时必须区分“内容重复”和“文风失真”。同一事实、记忆、意象、动作、身体感觉、情绪结论或对话争点在没有新增信息、选择或后果时反复出现，并已拖慢推进或削弱场景效果，才生成 EXCESSIVE_REPETITION；有新作用的伏笔回扣、刻意呼应和人物习惯不算重复。

正文出现以下机器化特征，且达到反复出现或实质损害人物声音、叙事沉浸和信息效率的程度时，才生成 STYLE_MISMATCH：解释人物已经通过动作表现出的情绪或结论；复述设定、计划或主题；密集使用“意识到、明白、意味着、不是……而是……、这一刻、仿佛命运或时代”等套句；段落长度、句式、比喻或收束方式机械同构；空泛升华、整齐排比和四字词堆叠；对白人人同声并把潜台词说尽。

孤立且符合人物、语境和节奏的一次使用不构成问题。不得为了寻找问题而惩罚正常的简洁叙述、必要过渡、类型文学惯用表达或有实际作用的重复。相同根因只能生成一个 finding，并合并最有代表性的连续逐字证据；不要把同一证据同时报告为 repetition、pacing 和 style，应该选择直接根因并给出可以执行的修复目标。
PROMPT;
    }

    /**
     * Canonical Summary 的事实压缩与字段分工约束。
     *
     * 对应版本由 config/prompts.php 的 policies.summary 管理；修改本文本时必须同步升级。
     */
    public static function summary(): string
    {
        return <<<'PROMPT'
摘要只记录 Canonical 正文明确支持的事实，并保留原文中的不确定性，不得把猜测、误解、传闻或人物判断改写成已经证实的事实。使用稳定的人名、地点、物件和具体动词，避免依赖“他、那里、这件事”等脱离上下文后无法检索的指代。

summary 只保留本章从起因、关键选择到结果及后续压力的最短因果链；key_events 只列会影响后续剧情或状态的事件；character_changes 只列人物的身体、位置、知识、目标、关系、身份或情绪基线发生的明确变化；unresolved_threads 只列章末仍未解决的具体风险、承诺、疑问或行动。没有符合条件的内容时返回空数组，不得凑项。

同一事实不要在多个字段中换词重复，除非它在不同字段中承担不可替代的作用。省略纯气氛、修辞、过程性小动作和没有后续影响的对白。不得评价文笔、解释主题、推测作者意图、替人物总结人生道理，也不得用空泛过渡、排比或升华句补足篇幅。
PROMPT;
    }
}
