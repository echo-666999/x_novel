<?php

namespace App\AI;

final class NarrativeProsePolicy
{
    public const VERSION = 'natural-prose-v1';

    public static function planning(): string
    {
        return '规划语言必须落到具体人物、动作、选择、阻力、因果和可观察变化。不得用“展现、体现、深化、凸显、升华、命运齿轮、时代洪流”等抽象标签代替实际剧情，也不得把主题结论预写成角色独白或旁白。场景目标和验收条件必须能由正文中的行为或结果验证，避免同义反复、整齐排比和宣传文案式句子。';
    }

    public static function writing(): string
    {
        return '正文必须像人物正在经历事件，不得像作者、模型或解说员在复述设定和解释主题。优先使用人物动作、带目的的对白、POV 可感知的环境与物件、身体反应和具体后果，让信息从场景中显露。不得反复使用“他意识到、他明白、这意味着、这不是……而是……、这一刻、仿佛命运或时代”等解释性套句；不得在每段末尾总结意义，不得堆叠整齐排比、同构短段、四字词组或空泛宏大词。不要把计划字段、人物标签和背景资料换一种说法塞回正文，也不要把潜台词全部说透。不同人物的对白应符合身份、知识和当下目的，允许停顿、误解、隐瞒与答非所问。不得为了规避套式而故意写成碎句、晦涩句或删掉必要因果。';
    }

    public static function reviewing(): string
    {
        return '文风维度还必须检查正文是否存在明显的机器生成痕迹：反复解释人物已经通过动作表现出的情绪或结论；复述设定、计划或主题；连续使用“意识到、明白、意味着、不是……而是……、这一刻、仿佛命运或时代”等套句；段落长度、句式或收束方式机械同构；空泛升华、排比和四字词堆叠；对白人人同声且把潜台词说尽。孤立且符合语境的一次使用不构成问题；只有反复出现或实质破坏人物声音、叙事沉浸和信息效率时，才生成 STYLE_MISMATCH finding，并合并同一根因的代表性证据。';
    }

    public static function summary(): string
    {
        return '摘要按发生顺序记录主体、事件、状态变化和未决后果，使用具体名词和动词。不得评价文笔、解释主题、替人物总结人生道理，也不得用空泛过渡、排比或升华句补足篇幅。';
    }
}
